# Run from the extracted submission root; no network or input writes.
root <- normalizePath('.',winslash='/',mustWork=TRUE)
source(file.path(root,'R/data_loader.R'));invisible(configure_musicpulse(root))
results <- Sys.getenv('MUSICPULSE_TEST_RESULTS',tempfile('musicpulse-smoke-'))
dir.create(results,recursive=TRUE,showWarnings=FALSE)
checks <- list()
check <- function(name,value){checks[[name]]<<-isTRUE(value);cat(if(isTRUE(value))'PASS'else'FAIL',name,'\n');if(!isTRUE(value))stop(name)}
paths<-c('app.R','run_app.R','requirements.R',list.files('R',pattern='[.]R$',full.names=TRUE))
check('all_runtime_R_parses',all(vapply(paths,function(p){parse(p);TRUE},logical(1))))
options(musicpulse.app_dir=root)
e<-new.env(parent=globalenv());source('app.R',local=e)
d<-e$data;f<-e$features;dy<-e$dynamics;c<-e$comparison;p<-e$previews
check('four_page_ui_no_conclusion',length(gregexpr('data-page="',as.character(e$ui),fixed=TRUE)[[1]])==4L&&!grepl('nav_conclusion',as.character(e$ui),fixed=TRUE))
check('KPI_from_data',identical(unname(as.integer(d$kpis)),c(2568L,95L,730L)))
check('Venn_from_data',identical(unname(as.integer(d$coverage)),c(400L,2073L,95L)))
check('unique_group_date_69350',nrow(d$daily)==69350L&&!anyDuplicated(d$daily[c('cross_platform_song_id','observation_date')]))
check('IDs_remain_strings',is.character(d$candidates$cross_platform_song_id)&&is.character(f$douyin$douyin_music_id)&&is.character(f$kugou$kugou_song_id))
check('date_type_window',inherits(d$bounds,'Date')&&identical(d$bounds,as.Date(c('2024-11-14','2026-11-13'))))
s<-e$summarise_window(d,d$bounds);order<-e$filter_explorer(s)
rc<-function(n)readr::read_csv(file.path('data/music_preview_research',n),col_types=readr::cols(.default=readr::col_character()),show_col_types=FALSE)
p1<-rc('page1_default_top30.csv');p3<-rc('page3_default_top10.csv')
check('default_first30_exact_order',identical(head(order$cross_platform_song_id,30),p1$candidate_id))
check('search_by_ID',identical(e$filter_explorer(s,p1$candidate_id[1])$cross_platform_song_id,p1$candidate_id[1]))
check('observed_union_identity',all(s$union_days==s$douyin_days+s$kugou_days-s$same_day_days))
fs<-e$page2_window_summary(f,d$bounds)
check('feature_six_categories',length(f$genre_order)==6&&length(f$mood_order)==6)
check('feature_counts_valid',all(fs$genre$count<=fs$genre$denominator)&all(fs$mood$count<=fs$mood$denominator))
check('native_feature_units_unique',all(vapply(fs$units,function(x)!anyDuplicated(x$unit_id),logical(1))))
check('duration_bins_keep_units',all(vapply(split(fs$duration_bins,fs$duration_bins$platform),function(x)sum(x$count)==x$denominator[1],logical(1))))
check('Douyin_duration_unverified',all(fs$duration$display_unit[fs$duration$platform=='Douyin']=='source units (unverified)'))
check('empty_keyword_selection',nrow(e$page2_keyword_summary(f$keywords,character(),character()))==0)
w<-e$dyn_window(dy,d$bounds);top<-e$dyn_top10(w,'All Songs',NULL,'union');matrix<-e$dyn_matrix(w,top)
check('default_Top10_exact_order',identical(top$cross_platform_song_id,p3$candidate_id))
check('matrix_same_Top10',setequal(matrix$cross_platform_song_id[!matrix$placeholder],top$cross_platform_song_id))
check('timeline_lead_formula',all(w$stats$lead_lag_days==as.integer(w$stats$kugou_first-w$stats$douyin_first),na.rm=TRUE))
cs<-e$cmp_summaries(e$cmp_filter(c))
check('paired_sample_95_68',identical(as.integer(table(factor(c$events$country,levels=c('China','United States')))),c(95L,68L)))
check('comparison_lead_formula',all(c$events$lead_days==as.integer(c$events$stream_date-c$events$short_date)))
check('same_day_definition',all((c$events$first_direction=='Same day')==(c$events$lead_days==0)))
check('comparison_source_counts',all(cs$countries$stream==c(62L,50L)))
check('independent_US_window',identical(c$periods$start_date,as.Date(c('2024-11-14','2020-06-01'))))
check('net_priority_signed_formula',all(abs(cs$genre$net_priority-100*(cs$genre$short_share-cs$genre$stream_share))<1e-8,na.rm=TRUE))
check('all_30_ready_local_sources',all(vapply(p1$candidate_id,function(id)!is.null(e$mp_preview_source(p,id)),logical(1))))
check('30_unique_audio_files',length(list.files('data/music_preview_research/audio',pattern='[.]mp3$'))==30L)
check('default10_verified_links',all(vapply(p3$candidate_id,function(id)!is.null(e$mp_kugou_link(p,id)),logical(1))))
check('runtime_data_all_inside_root',all(startsWith(attr(e$dashboard_data,'source_info')$files,paste0(root,'/'))))
check('data_sources_exactly_six',length(attr(e$dashboard_data,'source_info')$files)==6L)
readr::write_csv(data.frame(check=names(checks),passed=unlist(checks)),file.path(results,'smoke_results.csv'))
state<-list(kpis=d$kpis,coverage=d$coverage,page1=s,genre=fs$genre,mood=fs$mood,duration=fs$duration_bins,keywords=e$page2_keyword_summary(f$keywords,head(f$genre_order,5),head(f$mood_order,4)),top10=top,matrix=matrix,comparison=cs)
saveRDS(state,file.path(results,'r_analysis_state.rds'))
writeLines(capture.output(sessionInfo()),file.path(results,'sessionInfo.txt'))
cat('SMOKE PASSED:',length(checks),'checks. Results:',results,'\n')
